	var ATTRS = ['alt', 'aria-label', 'data-alt'];
	var root = document.documentElement;
	var enTitle = document.title;
	var current = 'en';

	function t(en) { return current === 'vi' && VI[en] ? VI[en] : en; }

	function apply(lang) {
		current = lang === 'vi' ? 'vi' : 'en';
		root.lang = current;
		document.title = t(enTitle);
		document.querySelectorAll('[data-i18n]').forEach(function (el) {
			if (el._en === undefined) el._en = el.innerHTML.trim();
			el.innerHTML = t(el._en);
		});
		ATTRS.forEach(function (a) {
			document.querySelectorAll('[' + a + ']').forEach(function (el) {
				var key = '_en_' + a;
				if (el[key] === undefined) el[key] = el.getAttribute(a);
				el.setAttribute(a, t(el[key]));
			});
		});
		document.querySelectorAll('.lang-toggle [data-lang]').forEach(function (b) {
			b.setAttribute('aria-pressed', String(b.dataset.lang === current));
		});
		document.dispatchEvent(new CustomEvent('langchange', { detail: current }));
	}

	function initial() {
		var q = new URLSearchParams(location.search).get('lang');
		if (q === 'vi' || q === 'en') return q;
		try { var saved = localStorage.getItem('lang'); if (saved) return saved; } catch (e) {}
		return /^vi\b/i.test(navigator.language || '') ? 'vi' : 'en';
	}

	window.i18n = { t: t, apply: apply, get lang() { return current; } };

	document.querySelectorAll('.lang-toggle [data-lang]').forEach(function (b) {
		b.addEventListener('click', function () {
			try { localStorage.setItem('lang', b.dataset.lang); } catch (e) {}
			apply(b.dataset.lang);
		});
	});

	var start = initial();
	if (start !== 'en') apply(start); else apply('en');
